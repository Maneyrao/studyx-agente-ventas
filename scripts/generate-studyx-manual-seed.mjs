#!/usr/bin/env node
/**
 * Generates the idempotent StudyX catalog/RAG seed from the owner-declared
 * source of truth in supabase/seed/data/studyx-manual.json.
 *
 * Regenerate: node scripts/generate-studyx-manual-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA_PATH = join(ROOT, 'supabase/seed/data/studyx-manual.json');
const OUTPUT_PATH = join(ROOT, 'supabase/seed/studyx-manual.sql');
const WORKSPACE_ID = 'b0000000-0000-4000-8000-000000000001';

const data = JSON.parse(readFileSync(DATA_PATH, 'utf8'));

if (data.source_of_truth !== true || data.courses.length !== 40) {
  throw new Error('The StudyX manual must declare exactly 40 explicit catalog courses.');
}

const codes = new Set();
for (const course of data.courses) {
  if (!course.code || !course.name || !course.academy || !course.classes || !course.description) {
    throw new Error(`Incomplete manual course: ${JSON.stringify(course)}`);
  }
  if (codes.has(course.code)) throw new Error(`Duplicate course code: ${course.code}`);
  codes.add(course.code);
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function compactDescription(course) {
  const firstSentence = course.description.match(/^.*?[.!?](?:\s|$)/)?.[0] ?? course.description;
  return `${course.academy}. ${course.classes} clases. ${firstSentence}`.slice(0, 390).trim();
}

const offeringRows = data.courses.map((course) => {
  const delivery = {
    modality: 'online',
    classes: course.classes,
    source: data.source_file,
  };
  const guardrails = {
    never_invent_price: true,
    forbidden_promises: [
      'certificación verificada',
      'título oficial',
      'homologación',
      'matrícula profesional',
      'salida laboral garantizada',
      'horarios de clases en vivo',
      'política de devoluciones',
    ],
  };
  const metadata = {
    canonical_source: 'studyx_manual_1',
    source_file: data.source_file,
    source_sha256: data.source_sha256,
    source_page: course.source_page,
    academy: course.academy,
    ...(course.aliases?.length ? { aliases: course.aliases } : {}),
    declared_classes: course.classes,
    total_price_usd: 360,
    payment_options_owner_confirmed: true,
    price_source: 'owner-confirmed 2026-08-20',
  };
  return `(
    gen_random_uuid(), ${sqlString(WORKSPACE_ID)}, ${sqlString(course.code)},
    ${sqlString(course.name)}, 'course', 'active', ${sqlString(compactDescription(course))},
    NULL, 'fixed', 360.00, 'USD', 'custom',
    ${sqlString(JSON.stringify({ language: 'Spanish' }))}::jsonb,
    ${sqlString(JSON.stringify(delivery))}::jsonb,
    ${sqlString(JSON.stringify(guardrails))}::jsonb,
    ${sqlString(JSON.stringify(metadata))}::jsonb
  )`;
});

const knowledgeRows = data.courses.map((course) => {
  const content = [
    `Curso: ${course.name}.`,
    `Academia: ${course.academy}.`,
    `Cantidad informada por el manual: ${course.classes} clases.`,
    course.description,
  ].join('\n');
  const metadata = {
    canonical_source: 'studyx_manual_1',
    source_file: data.source_file,
    source_sha256: data.source_sha256,
    source_page: course.source_page,
    course_code: course.code,
    academy: course.academy,
    declared_classes: course.classes,
  };
  return `(
    gen_random_uuid(), ${sqlString(WORKSPACE_ID)}, 'offering',
    ${sqlString(`Manual StudyX — ${course.name}`)}, ${sqlString(content)},
    'active', 1, ${sqlString(JSON.stringify(metadata))}::jsonb
  )`;
});

const academyCatalog = [...new Set(data.courses.map((course) => course.academy))]
  .map((academy) => {
    const names = data.courses.filter((course) => course.academy === academy).map((course) => course.name);
    return `${academy}: ${names.join('; ')}.`;
  })
  .join('\n');

const catalogContent = [
  'Catálogo oficial de StudyX según el manual definido por el propietario como fuente de verdad.',
  `Total explícito: ${data.courses.length} cursos en 9 academias.`,
  academyCatalog,
].join('\n');

const platformContent = [
  'El manual incluye orientación visual sobre el uso de la plataforma StudyX.',
  `Temas cubiertos: ${data.platform_topics.join('; ')}.`,
  'No contiene horarios concretos de clases ni fechas de inicio.',
].join('\n');

const ambiguityContent = data.ambiguities
  .map((item) => `${item.topic}: ${item.detail} Regla comercial: ${item.sales_status}.`)
  .join('\n');

const sourceMetadata = sqlString(JSON.stringify({
  canonical_source: 'studyx_manual_1',
  source_file: data.source_file,
  source_sha256: data.source_sha256,
}));

const sql = `-- GENERATED BY scripts/generate-studyx-manual-seed.mjs — DO NOT EDIT.
-- Canonical source: ${data.source_file}
-- SHA-256: ${data.source_sha256}
-- The 40 explicitly catalogued courses become active. Existing courses that
-- are absent from the manual are made inactive, never deleted.

BEGIN;
SET search_path TO public;

UPDATE workspaces
SET metadata = COALESCE(metadata, '{}'::jsonb) || ${sqlString(JSON.stringify({
  catalog_source: 'studyx_manual_1',
  catalog_source_file: data.source_file,
  catalog_source_sha256: data.source_sha256,
  catalog_active_count: data.courses.length,
  catalog_verified_at: data.extracted_at,
}))}::jsonb,
updated_at = now()
WHERE id = ${sqlString(WORKSPACE_ID)}::uuid;

INSERT INTO offerings (
  id, workspace_id, code, display_name, offering_type, status, description,
  value_proposition, price_type, price_amount, currency, billing_interval,
  audience, delivery, guardrails, metadata
) VALUES
${offeringRows.join(',\n')}
ON CONFLICT (workspace_id, code) DO UPDATE SET
  display_name = EXCLUDED.display_name,
  offering_type = EXCLUDED.offering_type,
  status = EXCLUDED.status,
  description = EXCLUDED.description,
  value_proposition = EXCLUDED.value_proposition,
  price_type = EXCLUDED.price_type,
  price_amount = EXCLUDED.price_amount,
  currency = EXCLUDED.currency,
  billing_interval = EXCLUDED.billing_interval,
  audience = EXCLUDED.audience,
  delivery = EXCLUDED.delivery,
  guardrails = EXCLUDED.guardrails,
  metadata = EXCLUDED.metadata,
  updated_at = now();

UPDATE offerings
SET status = 'inactive',
    metadata = COALESCE(metadata, '{}'::jsonb) || jsonb_build_object(
      'deactivated_by_catalog_sync', 'studyx_manual_1',
      'deactivated_at', now()
    ),
    updated_at = now()
WHERE workspace_id = ${sqlString(WORKSPACE_ID)}::uuid
  AND code NOT IN (${data.courses.map((course) => sqlString(course.code)).join(', ')})
  AND status = 'active';

-- Retire website-derived course sources so retrieval has one catalog truth.
UPDATE knowledge_sources
SET status = 'archived', updated_at = now()
WHERE workspace_id = ${sqlString(WORKSPACE_ID)}::uuid
  AND source_type = 'offering'
  AND COALESCE(metadata ->> 'canonical_source', '') <> 'studyx_manual_1'
  AND status <> 'archived';

-- Retire general statements that conflict with the owner-declared manual.
UPDATE knowledge_sources
SET status = 'archived', updated_at = now()
WHERE workspace_id = ${sqlString(WORKSPACE_ID)}::uuid
  AND title IN (
    'Qué vende StudyX',
    'Tamaño real del catálogo y qué no afirmar',
    'Modalidad: qué se puede afirmar sobre las clases'
  )
  AND status <> 'archived';

INSERT INTO knowledge_sources (
  id, workspace_id, source_type, title, content, status, version, metadata
) VALUES
${knowledgeRows.join(',\n')},
(
  gen_random_uuid(), ${sqlString(WORKSPACE_ID)}, 'business_profile',
  'Manual StudyX — Catálogo oficial', ${sqlString(catalogContent)},
  'active', 1, ${sourceMetadata}::jsonb
),
(
  gen_random_uuid(), ${sqlString(WORKSPACE_ID)}, 'process',
  'Manual StudyX — Uso de la plataforma', ${sqlString(platformContent)},
  'active', 1, ${sourceMetadata}::jsonb
),
(
  gen_random_uuid(), ${sqlString(WORKSPACE_ID)}, 'policy',
  'Manual StudyX — Ambigüedades que requieren confirmación', ${sqlString(ambiguityContent)},
  'active', 1, ${sourceMetadata}::jsonb
)
ON CONFLICT (workspace_id, title, version) DO UPDATE SET
  source_type = EXCLUDED.source_type,
  content = EXCLUDED.content,
  status = EXCLUDED.status,
  metadata = EXCLUDED.metadata,
  updated_at = now();

COMMIT;
`;

writeFileSync(OUTPUT_PATH, sql);
console.log(`${data.courses.length} offerings + ${data.courses.length + 3} knowledge sources -> ${OUTPUT_PATH}`);
