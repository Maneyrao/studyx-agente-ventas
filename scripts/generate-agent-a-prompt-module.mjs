import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sourcePath = resolve(root, 'docs/prompts/studyx-agent-a-canonical.md');
const outputPaths = [
  resolve(root, 'botpress-agent/src/prompts/studyx-agent-a-canonical.generated.ts'),
  resolve(root, 'src/shared/prompts/studyx-agent-a-canonical.generated.ts'),
];
// v109: v108 plus the 2026-11-04 bonus motive rules (motive from the current message; owner-authorized edit).
// v108: v107 plus the owner's 03-04/11 price guidance moved from retired runtime rules to model guidance (owner-authorized edit)
const expectedSha256 = '7b3da4520b8eba9155f6cd328e4e6b3eabcf1bb081d818e81d2a7b3e9dceba3b';
const prompt = readFileSync(sourcePath, 'utf8');
const sha256 = createHash('sha256').update(prompt).digest('hex');
const lineCount = prompt.match(/\n/g)?.length ?? 0;

if (lineCount !== 212) {
  throw new Error(`AGENT_A_CANONICAL_PROMPT_LINE_COUNT:${lineCount}`);
}
if (sha256 !== expectedSha256) {
  throw new Error(`AGENT_A_CANONICAL_PROMPT_SHA256:${sha256}`);
}

const generated = [
  '// Generated by scripts/generate-agent-a-prompt-module.mjs. Do not edit.',
  '// Source: docs/prompts/studyx-agent-a-canonical.md',
  `export const STUDYX_AGENT_A_CANONICAL_PROMPT = ${JSON.stringify(prompt)} as const;`,
  "export const STUDYX_AGENT_A_CANONICAL_PROMPT_VERSION = 'studyx-agent-a-canonical-v109' as const;",
  '',
].join('\n');

for (const outputPath of outputPaths) writeFileSync(outputPath, generated, 'utf8');
