export function inspectBotpressPreservedPublicationContracts({
  before,
  after,
  actionPatch = {},
  eventPatch = {},
  conversationTagPatch = {},
}) {
  return equal(after.actions ?? {}, { ...(before.actions ?? {}), ...actionPatch })
    && equal(after.states ?? {}, before.states ?? {})
    && equal(after.recurringEvents ?? {}, before.recurringEvents ?? {})
    && equal(after.events ?? {}, { ...(before.events ?? {}), ...eventPatch })
    && equal(after.message?.tags ?? {}, before.message?.tags ?? {})
    && equal(after.user?.tags ?? {}, before.user?.tags ?? {})
    && equal(after.conversation?.tags ?? {}, {
      ...(before.conversation?.tags ?? {}),
      ...conversationTagPatch,
    });
}

export function normalizeBotpressConfigurationForComparison(configuration) {
  assertRecord(configuration, 'configuration-comparison');
  assertRecord(configuration.data, 'configuration-comparison-data');
  assertRecord(configuration.schema, 'configuration-comparison-schema');
  assertRecord(configuration.schema.properties, 'configuration-comparison-properties');
  const data = {};
  for (const [key, property] of Object.entries(configuration.schema.properties)) {
    if (Object.prototype.hasOwnProperty.call(configuration.data, key)) {
      data[key] = configuration.data[key];
    } else if (property && typeof property === 'object'
      && Object.prototype.hasOwnProperty.call(property, 'default')) {
      data[key] = property.default;
    }
  }
  return { ...configuration, data };
}

export function planBotpressReviewedConfigurationUpdate({
  remoteConfiguration,
  generatedConfiguration,
}) {
  assertRecord(remoteConfiguration, 'remote-configuration');
  assertRecord(generatedConfiguration, 'generated-configuration');
  assertRecord(remoteConfiguration.data, 'remote-configuration-data');
  assertRecord(remoteConfiguration.schema, 'remote-configuration-schema');
  assertRecord(generatedConfiguration.schema, 'generated-configuration-schema');

  const remoteSchema = remoteConfiguration.schema;
  const generatedSchema = generatedConfiguration.schema;
  assertRecord(remoteSchema.properties, 'remote-configuration-properties');
  assertRecord(generatedSchema.properties, 'generated-configuration-properties');

  const remoteProperties = remoteSchema.properties;
  const generatedProperties = generatedSchema.properties;
  const remoteKeys = Object.keys(remoteProperties).sort();
  const generatedKeys = Object.keys(generatedProperties).sort();
  const removed = remoteKeys.filter((key) => !generatedKeys.includes(key));
  const added = generatedKeys.filter((key) => !remoteKeys.includes(key));
  if (removed.length > 0
    || added.some((key) => key !== allowedConfigurationPropertyName)
    || added.length > 1) {
    throw new Error(`CONTRACT_KEYS_CHANGED:configuration.schema.properties:added=${added.join(',')}:removed=${removed.join(',')}`);
  }

  const generatedReviewedProperty = generatedProperties[allowedConfigurationPropertyName];
  if (!equal(generatedReviewedProperty, allowedConfigurationProperty)) {
    throw new Error(`CONTRACT_CHANGED:configuration.schema.properties.${allowedConfigurationPropertyName}`);
  }
  const remoteReviewedProperty = remoteProperties[allowedConfigurationPropertyName];
  if (remoteReviewedProperty !== undefined
    && !previouslyReviewedConfigurationProperties.some((reviewed) => equal(remoteReviewedProperty, reviewed))) {
    throw new Error(`CONTRACT_CHANGED:configuration.schema.properties.${allowedConfigurationPropertyName}`);
  }

  for (const key of remoteKeys) {
    if (key !== allowedConfigurationPropertyName
      && !equal(remoteProperties[key], generatedProperties[key])) {
      throw new Error(`CONTRACT_CHANGED:configuration.schema.properties.${key}`);
    }
  }
  const withoutProperties = (schema) => Object.fromEntries(
    Object.entries(schema).filter(([key]) => key !== 'properties'),
  );
  if (!equal(withoutProperties(remoteSchema), withoutProperties(generatedSchema))) {
    throw new Error('CONTRACT_CHANGED:configuration.schema');
  }

  const hasStoredValue = Object.prototype.hasOwnProperty.call(
    remoteConfiguration.data,
    allowedConfigurationPropertyName,
  );
  const storedValue = remoteConfiguration.data[allowedConfigurationPropertyName];
  if (hasStoredValue && typeof storedValue !== 'boolean') {
    throw new Error(`CONFIGURATION_VALUE_CONFLICT:${allowedConfigurationPropertyName}`);
  }

  // The first publish of the default:false contract (remote schema absent or
  // still default:true, or no stored value) writes false once, turning OFF a
  // planner left ON by the old contract. After that the stored value is kept,
  // so an explicit owner flip to true in Botpress survives later publishes.
  const schemaTransition = !equal(remoteReviewedProperty, allowedConfigurationProperty);
  const changed = schemaTransition || !hasStoredValue;
  const desiredValue = changed ? allowedConfigurationProperty.default : storedValue;
  return {
    changed,
    configuration: changed
      ? {
          ...remoteConfiguration,
          data: {
            ...remoteConfiguration.data,
            [allowedConfigurationPropertyName]: desiredValue,
          },
          schema: generatedSchema,
        }
      : remoteConfiguration,
  };
}

export function inspectBotpressRemoteCode({ remoteCode, expectedSha256 }) {
  if (typeof remoteCode !== 'string') {
    return {
      status: 'unavailable',
      type: typeof remoteCode,
      byteLength: null,
      matches: null,
    };
  }

  const matches = createHash('sha256').update(remoteCode).digest('hex') === expectedSha256;
  return {
    status: matches ? 'verified' : 'mismatch',
    type: 'string',
    byteLength: Buffer.byteLength(remoteCode),
    matches,
  };
}

export function planBotpressAdditiveEventPatch({ remoteEvents, generatedEvents }) {
  assertRecord(remoteEvents, 'remote');
  assertRecord(generatedEvents, 'generated');

  const remoteKeys = Object.keys(remoteEvents).sort();
  const generatedKeys = Object.keys(generatedEvents).sort();
  const removed = remoteKeys.filter((key) => !generatedKeys.includes(key));
  const added = generatedKeys.filter((key) => !remoteKeys.includes(key));

  if (removed.length > 0 || added.some((key) => key !== allowedEventName) || added.length > 1) {
    throw new Error(`CONTRACT_KEYS_CHANGED:events:added=${added.join(',')}:removed=${removed.join(',')}`);
  }

  for (const key of remoteKeys) {
    if (!eventsEqual(remoteEvents[key], generatedEvents[key])) {
      throw new Error(`CONTRACT_CHANGED:events.${key}`);
    }
  }

  const reviewedEvent = generatedEvents[allowedEventName];
  if (reviewedEvent !== undefined && !eventsEqual(reviewedEvent, allowedEventContract)) {
    throw new Error(`CONTRACT_CHANGED:events.${allowedEventName}`);
  }

  return added.length === 1
    ? { [allowedEventName]: reviewedEvent }
    : {};
}

export function planBotpressAdditiveConversationTagPatch({ remoteTags, generatedTags }) {
  assertRecord(remoteTags, 'remote-conversation-tags');
  assertRecord(generatedTags, 'generated-conversation-tags');

  const remoteKeys = Object.keys(remoteTags).sort();
  const generatedKeys = Object.keys(generatedTags).sort();
  const removed = remoteKeys.filter((key) => !generatedKeys.includes(key));
  const added = generatedKeys.filter((key) => !remoteKeys.includes(key));

  if (removed.some((key) => !allowedRemoteOnlyConversationTagNames.has(key))
    || added.some((key) => !Object.prototype.hasOwnProperty.call(allowedConversationTagContracts, key))) {
    throw new Error(`CONTRACT_KEYS_CHANGED:conversation.tags:added=${added.join(',')}:removed=${removed.join(',')}`);
  }

  for (const key of remoteKeys.filter((key) => generatedKeys.includes(key))) {
    if (!equal(remoteTags[key], generatedTags[key])) {
      throw new Error(`CONTRACT_CHANGED:conversation.tags.${key}`);
    }
  }

  for (const key of added) {
    const reviewedTag = generatedTags[key];
    if (!equal(reviewedTag, allowedConversationTagContracts[key])) {
      throw new Error(`CONTRACT_CHANGED:conversation.tags.${key}`);
    }
  }

  return Object.fromEntries(added.map((key) => [key, generatedTags[key]]));
}

export function planBotpressReviewedActionPatch({ remoteActions, generatedActions }) {
  assertRecord(remoteActions, 'remote-actions');
  assertRecord(generatedActions, 'generated-actions');

  const remoteKeys = Object.keys(remoteActions).sort();
  const generatedKeys = Object.keys(generatedActions).sort();
  const generatedOnly = generatedKeys.filter((key) => !remoteKeys.includes(key));
  if (generatedOnly.length > 0) {
    throw new Error(`CONTRACT_KEYS_CHANGED:actions:generated_only=${generatedOnly.join(',')}`);
  }
  const remoteOnly = remoteKeys.filter((key) => !generatedKeys.includes(key));
  const unknownRemoteOnly = remoteOnly.filter((key) => !allowedRemoteOnlyActionNames.has(key));
  if (unknownRemoteOnly.length > 0) {
    throw new Error(`CONTRACT_KEYS_CHANGED:actions:remote_only=${unknownRemoteOnly.join(',')}`);
  }

  for (const key of generatedKeys) {
    if (key !== allowedActionName
      && !equal(normalizedContract(remoteActions[key]), normalizedContract(generatedActions[key]))) {
      throw new Error(`CONTRACT_CHANGED:actions.${key}`);
    }
  }

  const remoteAction = remoteActions[allowedActionName];
  const generatedAction = generatedActions[allowedActionName];
  if (equal(normalizedContract(remoteAction), normalizedContract(generatedAction))) return {};

  const remoteDigest = contractDigest(remoteAction);
  const generatedDigest = contractDigest(generatedAction);
  if (remoteDigest !== allowedRemoteReportDeliverySha256
    || generatedDigest !== allowedGeneratedReportDeliverySha256) {
    throw new Error(
      `UNREVIEWED_ACTION_CONTRACT:${allowedActionName}:${remoteDigest}:${generatedDigest}`,
    );
  }

  return { [allowedActionName]: generatedAction };
}

export function buildBotpressAdditiveEventUpdate({
  botId,
  code,
  eventPatch,
  conversationTagPatch = {},
  actionPatch = {},
  configurationPlan = /** @type {any} */ (null),
}) {
  if (typeof botId !== 'string' || botId.length === 0) throw new Error('INVALID_BOT_ID');
  if (typeof code !== 'string' || code.length === 0) throw new Error('INVALID_BOT_CODE');
  assertRecord(eventPatch, 'patch');
  assertRecord(conversationTagPatch, 'conversation-tag-patch');
  assertRecord(actionPatch, 'action-patch');
  if (configurationPlan !== null) {
    assertRecord(configurationPlan, 'configuration-plan');
    if (typeof configurationPlan.changed !== 'boolean') {
      throw new Error('INVALID_CONFIGURATION_PLAN');
    }
    assertRecord(configurationPlan.configuration, 'configuration-update');
    if (configurationPlan.changed) {
      if (configurationPlan.configuration.data?.[allowedConfigurationPropertyName] !== allowedConfigurationProperty.default
        || !equal(
          configurationPlan.configuration.schema?.properties?.[allowedConfigurationPropertyName],
          allowedConfigurationProperty,
        )) {
        throw new Error('UNREVIEWED_CONFIGURATION_PATCH');
      }
    }
  }

  const eventKeys = Object.keys(eventPatch);
  if (eventKeys.some((key) => key !== allowedEventName) || eventKeys.length > 1) {
    throw new Error('UNREVIEWED_EVENT_PATCH');
  }
  if (eventKeys.length === 1 && !eventsEqual(eventPatch[allowedEventName], allowedEventContract)) {
    throw new Error(`CONTRACT_CHANGED:events.${allowedEventName}`);
  }

  const conversationTagKeys = Object.keys(conversationTagPatch);
  if (conversationTagKeys.some((key) => (
    !Object.prototype.hasOwnProperty.call(allowedConversationTagContracts, key)
  ))) {
    throw new Error('UNREVIEWED_CONVERSATION_TAG_PATCH');
  }
  for (const key of conversationTagKeys) {
    if (!equal(conversationTagPatch[key], allowedConversationTagContracts[key])) {
      throw new Error(`CONTRACT_CHANGED:conversation.tags.${key}`);
    }
  }

  const actionKeys = Object.keys(actionPatch);
  if (actionKeys.some((key) => key !== allowedActionName) || actionKeys.length > 1) {
    throw new Error('UNREVIEWED_ACTION_PATCH');
  }
  if (actionKeys.length === 1
    && contractDigest(actionPatch[allowedActionName]) !== allowedGeneratedReportDeliverySha256) {
    throw new Error(`CONTRACT_CHANGED:actions.${allowedActionName}`);
  }

  return {
    id: botId,
    code,
    ...(eventKeys.length === 1 ? { events: eventPatch } : {}),
    ...(conversationTagKeys.length > 0 ? { conversation: { tags: conversationTagPatch } } : {}),
    ...(actionKeys.length === 1 ? { actions: actionPatch } : {}),
    ...(configurationPlan?.changed ? { configuration: configurationPlan.configuration } : {}),
  };
}
