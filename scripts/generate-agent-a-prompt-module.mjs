import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const sourcePath = resolve(root, 'docs/prompts/studyx-agent-a-canonical.md');
const outputPath = resolve(root, 'botpress-agent/src/prompts/studyx-agent-a-canonical.generated.ts');
// v64: conserva la voz de Lisandro y agrega recuperación natural para
// audios no transcritos y formatos que el canal no puede interpretar.
const expectedSha256 = '6217b2df90ac1f2cae2458e3e55b1b48e0fd31205e7ec688e202e8aa31ed550b';
const prompt = readFileSync(sourcePath, 'utf8');
const sha256 = createHash('sha256').update(prompt).digest('hex');
const lineCount = prompt.match(/\n/g)?.length ?? 0;

if (lineCount !== 63) {
  throw new Error(`AGENT_A_CANONICAL_PROMPT_LINE_COUNT:${lineCount}`);
}
if (sha256 !== expectedSha256) {
  throw new Error(`AGENT_A_CANONICAL_PROMPT_SHA256:${sha256}`);
}

const generated = [
  '// Generated by scripts/generate-agent-a-prompt-module.mjs. Do not edit.',
  '// Source: docs/prompts/studyx-agent-a-canonical.md',
  `export const STUDYX_AGENT_A_CANONICAL_PROMPT = ${JSON.stringify(prompt)} as const;`,
  "export const STUDYX_AGENT_A_CANONICAL_PROMPT_VERSION = 'studyx-agent-a-canonical-v64' as const;",
  '',
].join('\n');

writeFileSync(outputPath, generated, 'utf8');
