/** Deterministic payment reservation outcomes (reserve-payment-link / replace-pending-checkout). */
const PAYMENT_RESERVATION_REJECTIONS_V1 = new Set([
  'PROMOTION_NOT_AUTHORIZED', 'PROMOTION_SNAPSHOT_INCOMPLETE', 'PROMOTION_SNAPSHOT_NOT_SEALED',
  'COURSE_BONUS_DISABLED', 'IDEMPOTENCY_KEY_CONFLICT', 'PAYMENT_LINK_INVALID', 'PLAN_INVALID',
  'PAYMENT_WORKSPACE_NOT_FOUND', 'CHECKOUT_REPLACEMENT_BLOCKED', 'CHECKOUT_REPLACEMENT_NOT_FOUND',
  'CHECKOUT_REPLACEMENT_IDENTITY_MISMATCH', 'CHECKOUT_ALREADY_SUPERSEDED', 'CHECKOUT_REPLACEMENT_CONTACT_MISSING',
  'CHECKOUT_REPLACEMENT_UNSUPPORTED', 'CHECKOUT_REPLACEMENT_NOT_RESERVED',
  // Technical link configuration failure (materializer): an unexecuted effect, not an unreadable turn.
  'LINK_CONFIG_MISSING',
])

/**
 * A payment reservation failure rejects the payment-link EFFECT with its real
 * code. It is never an unreadable turn (incident B, owner 2026-11-10).
 */
export function paymentReservationRejectionSubjectsV1(reason: string): string[] | null {
  return PAYMENT_RESERVATION_REJECTIONS_V1.has(reason)
    ? ['send_payment_link', `payment_reservation:${reason.toLowerCase()}`]
    : null
}

/**
 * A rejection of the payment-link request itself or of its course/plan resolution
 * (validation). A technical `payment_reservation:*` failure is not retried as a link.
 */
export function rejectsPaymentLinkRequestV1(rejection: TurnRejectionV1): boolean {
  return rejection.rejections.some((reason) => (reason.subject === 'send_payment_link'
    || reason.code === 'PLAN_NOT_SELECTED' || reason.code === 'COURSE_NOT_RESOLVED')
    && !reason.subject.startsWith('payment_reservation:'))
    && !rejection.rejections.some((reason) => reason.subject.startsWith('payment_reservation:'))
}

/** Fence every effect; the continuation's own safe move carries conversation state. */
export function fencedAgentARequestV1() {
  return { conversation_only: true as const }
}

/** Rebuild only promotion permissions from the current claim, never from stale feedback. */
export function authorizedPromotionActionsV1(context: AgentAContextV1): string[] {
  const actions = ['none']
  const courseBonus = context.capabilities.course_bonus
  if (courseBonus?.may_schedule_checkin) actions.push('schedule_price_objection_checkin')
  if (courseBonus?.may_request_review) actions.push('request_promotion_review')
  if (courseBonus?.enabled === true && courseBonus.may_offer_bonus === true) {
    actions.push('offer_course_bonus')
  }
  if (courseBonus?.may_accept_offer) actions.push('accept_promotion')
  return actions
}

/**
 * A continuation may keep an invitation only while the persisted lifecycle
 * still authorizes one. Opportunity and timing belong to Agent A: this gate
 * deliberately does not inspect customer wording, course selection or sales
 * stage heuristics such as "useful moment".
 */
export function continuationCallOfferAuthorizedV1(context: AgentAContextV1): boolean {
  const state = context.commercial_state
  const completedHistoricalCall = state.active_call == null
    && state.last_call_result != null
    && state.call_preference === 'call'
    && state.call_offer_status === 'accepted'
    && state.awaiting_reply === 'none'
    && state.stage !== 'payment_link_sent'
    && state.stage !== 'closed'

  if (!context.capabilities.may_offer_call || state.call_offer_count >= 2) return false
  if (state.stage === 'handoff' || state.stage === 'closed'
      || state.stage === 'payment_link_sent' || state.payment_reported) return false
  if (state.active_call != null || state.call_offer_status === 'offered') return false
  if (state.call_preference === 'chat' || state.call_preference === 'declined'
      || state.call_offer_status === 'declined') return false
  if (!completedHistoricalCall && (
    state.call_preference === 'call' || state.call_offer_status === 'accepted'
  )) return false
  return true
}

/** Structural results only. Customer wording is always generated by Agent A. */
export function plannerlessActionFeedbackV1(input: {
  readonly failure_code: string
  readonly context: AgentAContextV1
  readonly rejection_id: string
}): TurnRejectionV1 {
  const prefix = 'PLANNERLESS_PROPOSAL_REJECTED:'
  const reasons = input.failure_code.startsWith(prefix)
    ? input.failure_code.slice(prefix.length).split(',').flatMap(item => {
        const [code, ...subjectParts] = item.trim().split(':')
        const parsed = TurnRejectionCodeSchema.safeParse(code)
        const subject = subjectParts.join(':')
        return parsed.success && /^[a-z0-9_:.-]{1,160}$/iu.test(subject)
          ? [{ code: parsed.data, subject }] : []
      })
    : []
  const missing = reasons.filter(item => item.code === 'MISSING_INTAKE').map(item => item.subject)
  const requirements = input.context.capabilities.required_contact_fields
  const subjects = reasons.map(item => item.subject)
  const purposeMissing = subjects.some(subject => subject === 'request_call_now' || subject.startsWith('call'))
    ? requirements?.call
    : subjects.some(subject => subject.includes('payment') || subject.includes('send_test_payment_link'))
      ? requirements?.payment
      : requirements?.identity
  const actions = authorizedPromotionActionsV1(input.context)
  return {
    schema_version: 1, rejection_id: input.rejection_id, attempt: 1,
    rejections: reasons.length ? reasons : [{ code: 'ACTION_NOT_AUTHORIZED', subject: 'action' }],
    authorized_alternatives: {
      fact_ids: [], actions,
      missing_information: [...new Set([
        ...(purposeMissing ?? input.context.capabilities.intake_missing ?? []),
        ...missing,
      ])],
    },
  }
}

/** A bounded continuation may retain only an effect explicitly re-authorized by the receipt. */
export async function continueAgentAAfterActionFeedbackV1(input: {
  readonly context: AgentAContextV1
  readonly rejection: TurnRejectionV1
  readonly apiKey: string
  readonly signal: AbortSignal
  readonly model: string
  /** Keep an independently authorized call/payment obligation alive. */
  readonly effects_allowed?: boolean
  readonly customer_call_interpretation?: CustomerCallInterpretationV1
  readonly on_provider_request?: () => void
  readonly generate?: typeof generateDeepSeekAgentATurnProposalV1
}) {
  const allowedActions = input.effects_allowed
    ? input.rejection.authorized_alternatives.actions
    : ['none']
  const context = { ...input.context, turn_rejection: {
    ...input.rejection,
    authorized_alternatives: { ...input.rejection.authorized_alternatives, actions: allowedActions },
  } }
  const rawGenerated = await (input.generate ?? generateDeepSeekAgentATurnProposalV1)({
    context, apiKey: input.apiKey, signal: input.signal, model: input.model,
    conversation_only: input.effects_allowed !== true,
    on_provider_request: input.on_provider_request,
  })
  const generated = input.customer_call_interpretation ? { ...rawGenerated,
    proposal: bindCustomerCallInterpretationV1(input.customer_call_interpretation, rawGenerated.proposal, context) } : rawGenerated
  const proposedAction = generated.proposal.proposed_action.type
  const callOfferAuthorized = generated.proposal.response.call_offer == null
    || continuationCallOfferAuthorizedV1(context)
  if (!allowedActions.includes(proposedAction) || !callOfferAuthorized) {
    throw new Error('PLANNERLESS_PROPOSAL_REJECTED:ACTION_NOT_AUTHORIZED:continuation')
  }
  const resolved = await resolveAgentAPlannerlessProposalV2({
    initial: generated, context, repair_enabled: false, semantic_rejections: 'advisory',
    rejection_id: input.rejection.rejection_id,
    repair: async () => { throw new Error('AGENT_A_CONTINUATION_REPAIR_NOT_ALLOWED') },
  })
  // The continuation owns wording and classification corrections; the initial
  // customer call controls remain bound when this is a repair of the same turn.
  return resolved.effective
}
