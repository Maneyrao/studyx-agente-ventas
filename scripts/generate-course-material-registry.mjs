#!/usr/bin/env node
/**
 * Registers the official WhatsApp material of the 57 manual courses by sha256 (owner decision 2026-11-05):
 *   - image:  studyx-material-whatsapp/imagenes/NN_Name.png   (outside git; staged by stage-course-programs.mjs)
 *   - ficha:  docs/authority/material-gabi-2026-11-03/fichas_pdf/NN_Name.pdf (in git)
 *   - program: the official programme PDF when one exists (programas-studyx-pdf.json), registered separately.
 * Output: src/shared/catalog/course-material.generated.ts. The mapping manual name -> offering code comes from
 * the fichas data (scripts/generate-gabi-fichas-seed.mjs); the index CSV gives each course its image and ficha file.
 *
 *   node scripts/generate-course-material-registry.mjs [imagesDir]
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OFFERING_CODES } from './generate-studyx-programs-seed.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MATERIAL = join(ROOT, 'docs/authority/material-gabi-2026-11-03');
export const DEFAULT_IMAGES_DIR = '/Users/tmaneyro22/Documents/AGENTE IA/studyx-material-whatsapp/imagenes';
const OUTPUT = join(ROOT, 'src/shared/catalog/course-material.generated.ts');

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

function parseCsvLine(line) {
  const cells = []; let cell = ''; let quoted = false;
  for (const char of line) {
    if (char === '"') quoted = !quoted; else if (char === ',' && !quoted) { cells.push(cell); cell = ''; } else cell += char;
  }
  cells.push(cell);
  return cells;
}

export function buildRegistry(imagesDir = DEFAULT_IMAGES_DIR) {
  const fichas = JSON.parse(readFileSync(join(ROOT, 'supabase/seed/data/fichas-gabi-2026-11-03.json'), 'utf8'));
  const codeByName = new Map(fichas.courses.map(course => [course.manual_name, course.offering_code]));
  const programs = JSON.parse(readFileSync(join(ROOT, 'supabase/seed/data/programas-studyx-pdf.json'), 'utf8')).programs;
  const programByCode = new Map(programs.flatMap(program => OFFERING_CODES[program.slug] ? [[OFFERING_CODES[program.slug], program]] : []));
  const rows = readFileSync(join(MATERIAL, 'indice_para_el_agente.csv'), 'utf8').replace(/^﻿/u, '').split(/\r?\n/u).filter(Boolean).slice(1).map(parseCsvLine);
  const entries = [];
  for (const [name, , imagePath, fichaPath] of rows) {
    if (!fichaPath) continue;                                    // "(General) Beneficios Studyx" has no ficha and no course
    const code = codeByName.get(name);
    if (!code) throw new Error(`UNMAPPED_MANUAL_COURSE:${name}`);
    const imageFile = imagePath.split('/').at(-1);
    const fichaFile = fichaPath.split('/').at(-1);
    const program = programByCode.get(code) ?? null;
    entries.push({
      code, name, image_file: imageFile, image_sha256: sha256(join(imagesDir, imageFile)),
      ficha_file: fichaFile, ficha_sha256: sha256(join(MATERIAL, 'fichas_pdf', fichaFile)),
      program_slug: program?.slug ?? null, program_sha256: program?.sha256 ?? null,
    });
    const last = entries.at(-1);
    // Identity of the delivered pair (PDF + image), computed here so runtime code needs no crypto.
    last.version = createHash('sha256').update(`${last.program_sha256 ?? last.ficha_sha256}:${last.image_sha256}`).digest('hex').slice(0, 12);
  }
  if (entries.length !== 57 || new Set(entries.map(entry => entry.code)).size !== 57) throw new Error(`MANUAL_COURSE_COUNT:${entries.length}`);
  const benefits = 'imagenes/00_Beneficios_Studyx.png';
  return { entries, benefits: { file: benefits.split('/').at(-1), sha256: sha256(join(imagesDir, benefits.split('/').at(-1))) } };
}

export function renderRegistry(registry) {
  const q = (value) => (value === null ? 'null' : `'${value.replace(/'/gu, "\\'")}'`);
  const lines = registry.entries.map(e => `  [${q(e.code)}, ${q(e.name)}, ${q(e.image_file)}, ${q(e.image_sha256)}, ${q(e.ficha_file)}, ${q(e.ficha_sha256)}, ${q(e.program_slug)}, ${q(e.program_sha256)}, ${q(e.version)}],`);
  return `// Generated by scripts/generate-course-material-registry.mjs. Do not edit.
// Official WhatsApp material of the 57 manual courses, registered by sha256 (owner decision 2026-11-05).
/** [offering_code, manual name, image file, image sha256, ficha file, ficha sha256, program slug | null, program sha256 | null, pair version] */
export type CourseMaterialRowV1 = readonly [string, string, string, string, string, string, string | null, string | null, string];
export const COURSE_MATERIAL_ROWS_V1: readonly CourseMaterialRowV1[] = [
${lines.join('\n')}
];
export const BENEFITS_IMAGE_V1 = { file: ${q(registry.benefits.file)}, sha256: ${q(registry.benefits.sha256)} } as const;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, renderRegistry(buildRegistry(process.argv[2] ?? DEFAULT_IMAGES_DIR)));
  console.log(`57 courses -> ${OUTPUT}`);
}
